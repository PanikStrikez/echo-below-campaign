const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require('playwright');

(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try{
    const context=await browser.newContext({viewport:{width:1512,height:982}});
    const page=await context.newPage();const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('dialog',dialog=>dialog.accept());
    await page.goto('file://'+path.resolve(__dirname,'../Session-01-TV-Display.html'));
    await page.locator('#dm-app.hybrid-ui.hybrid-home').waitFor();
    assert(await page.locator('#hybrid-home').isVisible());
    assert(await page.locator('#hybrid-tv-now-top').isVisible());
    await page.getByRole('button',{name:/Start combat/}).click();
    assert(await page.locator('#dm-stage').isVisible());
    await page.locator('#hybrid-top-more summary').click();
    await page.locator('#hybrid-top-more').getByRole('button',{name:'Prepare',exact:true}).click();
    assert(await page.locator('#dm-app').evaluate(node=>node.classList.contains('prep-mode')));
    assert(await page.locator('.dm-main').isVisible());
    await page.locator('#mode-review').click();
    assert(await page.locator('#dm-app').evaluate(node=>node.classList.contains('review-mode')));
    await page.locator('#mode-run').click();
    await page.getByRole('button',{name:'Scene',exact:true}).first().click();
    assert(await page.locator('#hybrid-scene-view').isVisible());
    await page.locator('#hybrid-top-more summary').click();
    await page.locator('#hybrid-top-more').getByRole('button',{name:'Party',exact:true}).click();
    assert(await page.locator('#cockpit-tools-Party').isVisible(),'advanced tools remain reachable');
    await page.locator('#hybrid-top-more summary').click();
    await page.locator('#hybrid-top-more').getByRole('button',{name:'Settings',exact:true}).click();
    await page.getByRole('button',{name:'Use classic layout'}).click();
    await page.locator('#dm-app.cockpit').waitFor();
    assert.equal(await page.locator('#dm-app.hybrid-ui').count(),0);
    await page.locator('[data-cockpit-nav="Settings"]').click();
    await page.getByRole('button',{name:'Use redesigned layout'}).click();
    await page.locator('#dm-app.hybrid-ui.hybrid-home').waitFor();
    assert(await page.locator('#hybrid-atlas-slot .atlas-viewport').isVisible());
    const tablet=await browser.newContext({viewport:{width:820,height:1180}});
    const small=await tablet.newPage();const smallErrors=[];
    small.on('pageerror',error=>smallErrors.push(error.message));
    await small.goto('file://'+path.resolve(__dirname,'../Session-01-TV-Display.html'));
    await small.locator('#dm-app.hybrid-ui').waitFor();
    const widths=await small.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert(widths.document<=widths.viewport+2,`tablet horizontal overflow: ${JSON.stringify(widths)}`);
    const narrow=await browser.newContext({viewport:{width:640,height:900}});
    const compact=await narrow.newPage();const narrowErrors=[];
    compact.on('pageerror',error=>narrowErrors.push(error.message));
    await compact.goto('file://'+path.resolve(__dirname,'../Session-01-TV-Display.html'));
    await compact.locator('#hybrid-home').waitFor();
    await compact.getByRole('button',{name:/Explore.*Follow leads/}).click();
    assert(await compact.locator('.hybrid-pilot-side > .hybrid-primary').isVisible(),'small DM screen retains TV staging');
    const compactWidths=await compact.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert(compactWidths.document<=compactWidths.viewport+2,`small-screen horizontal overflow: ${JSON.stringify(compactWidths)}`);
    assert.deepEqual(errors,[]);assert.deepEqual(smallErrors,[]);assert.deepEqual(narrowErrors,[]);
    console.log('DM UI passed: Launchpad, scene, Prep/Run/Review, combat map, advanced controls, classic fallback, and 820px/640px layouts.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
