/* Narrow final visual check, using the existing isolated practice harness. */
'use strict';
const assert=require('node:assert/strict');
module.exports=async function floorVisual(h){
  const {page,tv,api,phoneBase,pass,screenshot,atlasBoard,locate,preservedState,phoneSnapshot}=h;
  const master=await page.evaluate(()=>ECHO_ATLAS.proposal('undermountain-proposal-level-1'));
  assert(master?.isFloorMaster);
  const board=await page.evaluate(id=>ECHO_ATLAS_DATA.boards.find(b=>b.proposalId===id).id,master.id);
  const chain=await page.evaluate(id=>ECHO_ATLAS.breadcrumbs(ECHO_ATLAS_DATA,id),board);
  for(const location of new Set(chain.map(b=>b.locationId).filter(Boolean)))await locate(location);
  await atlasBoard(board);
  await page.evaluate(id=>__atlasHost.prepareMap(ECHO_ATLAS.proposal(id)),master.id);
  await page.locator('#context-scene').getByRole('button',{name:'Show on TV',exact:true}).click();
  const section=await page.evaluate(id=>ECHO_ATLAS.proposals().filter(p=>p.floorProposalId===id&&!p.isFloorMaster)[2],master.id);
  assert(section);
  await page.evaluate(id=>__mapHost.focusFloor(id),section.id);
  await page.locator('#context-scene').getByRole('button',{name:'Show on TV',exact:true}).click();
  await page.waitForFunction(()=>{const img=document.querySelector('#dm-stage .scene-image');return img?.complete&&img.naturalWidth>0;});
  const shade=await page.evaluate(()=>[...document.querySelector('#dm-stage .floor-fog-canvas').getContext('2d').getImageData(0,0,1,1).data]);
  assert(shade[3]>=96&&shade[3]<=98,'Unrevealed DM shade should be 38% opaque');
  const publicImage=(await phoneSnapshot()).public.presentation.sceneImage;
  assert(publicImage.startsWith('data:image/png;base64,'));
  assert(await page.evaluate(async src=>{const img=new Image();img.src=src;await img.decode();const c=document.createElement('canvas');c.width=16;c.height=16;const x=c.getContext('2d');x.drawImage(img,0,0,16,16);const p=x.getImageData(0,0,16,16).data;for(let n=4;n<p.length;n+=4)if(p[n]!==p[0]||p[n+1]!==p[1]||p[n+2]!==p[2]||p[n+3]!==255)return false;return p[3]===255;},publicImage),'Player floor must remain opaque');
  await screenshot(page,'Workflow-DM-Section.png');
  pass('DM floor uses readable 38% shade while public unrevealed artwork remains opaque');
  const before=await preservedState();
  const workflowBoard=await page.evaluate(()=>ECHO_ATLAS_DATA.boards.find(b=>b.dungeonWorkflow).id);
  await atlasBoard(workflowBoard);
  await page.getByRole('button',{name:'Expand atlas',exact:true}).click();
  await page.getByText('Dungeon preparation & routes · DM only',{exact:true}).click();
  await page.getByText('Private route diagram',{exact:true}).click();
  const diagram=page.locator('.campaign-atlas img[src="atlas/undermountain/Undermountain-Route-DM.svg"]');
  await diagram.evaluate(img=>img.decode());
  assert(await diagram.evaluate(img=>img.naturalWidth===1400&&img.naturalHeight===850));
  await diagram.scrollIntoViewIfNeeded();
  await screenshot(diagram,'Workflow-Private-Route-Diagram.png');
  assert.deepEqual(await preservedState(),before,'Opening the private route diagram changed campaign state');
  assert(!JSON.stringify(await phoneSnapshot()).includes('Undermountain-Route-DM'));
  assert.equal(await tv.locator('img[src*="Undermountain-Route-DM"]').count(),0);
  assert.equal((await api.get(phoneBase+'/atlas/undermountain/Undermountain-Route-DM.svg')).status(),404);
  pass('Private route diagram decodes at native size, leaves campaign state unchanged, and is absent from TV/phone');
};
